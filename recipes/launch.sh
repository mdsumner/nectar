#!/bin/bash
# launch.sh: the command-line way to launch a recipe server, with the extras the dashboard snippet doesn't do. It packs
# this folder into cloud-init user-data and boots a server, which then builds itself. Nothing else is needed from GitHub.
#
# Usage:  launch.sh NAME --key KEYPAIR [options]
#   --flavor F          default m3.small
#   --image I           default "NeCTAR Ubuntu 26.04 LTS (Resolute) amd64" (GDAL comes from images built on this release)
#   --secgroups a,b     default default,ssh (add a group opening 80+443 with --fqdn)
#   --az Z              availability zone (required with a volume: it must match the volume's)
#   --new-volume GB     create a volume NAME-home and keep home directories and Docker on it
#   --volume ID         reuse an existing detached volume
#   --home DIR          where homes live; default /home, or /mnt/data/home with a volume
#   --users FILE        accounts, see layers/60-users.sh (default: one `rstudio` login)
#   --fqdn FQDN         serve RStudio at https://FQDN/rstudio/ (default: none, SSH tunnel only)
#   --email ADDR        Let's Encrypt contact, with --fqdn
#   --rust              add the Rust toolchain
#   --jupyter           add JupyterLab (R and Python kernels), reached through the SSH tunnel like RStudio
#   --python-full       lift the full Python geo stack (gdal-r-python: rasterio, geopandas, xarray, ...); ~3 GB more disk
#   --gdal-image IMG    lift GDAL from another gdal-r-ci image (default ghcr.io/hypertidy/gdal-system:latest)
#   --dry-run           write the user-data and print the command; create nothing
# Needs: your project's OpenStack credentials in the environment and `openstack` on PATH (or $OPENSTACK).
set -euo pipefail
O=${OPENSTACK:-openstack}
HERE=$(cd "$(dirname "$0")" && pwd)
NAME=${1:?usage: launch.sh NAME --key KEYPAIR [options]}; shift
KEY= VOLID= NEWGB= USERS= FQDN= EMAIL= DRY= RUST= AZ= HOMEDIR= JUPYTER= GDAL_IMAGE=
FLAVOR=m3.small IMAGE="NeCTAR Ubuntu 26.04 LTS (Resolute) amd64" SGS=default,ssh
while [ $# -gt 0 ]; do case $1 in
  --volume) VOLID=$2; shift 2;; --new-volume) NEWGB=$2; shift 2;; --users) USERS=$2; shift 2;; --home) HOMEDIR=$2; shift 2;;
  --fqdn) FQDN=$2; shift 2;; --email) EMAIL=$2; shift 2;; --flavor) FLAVOR=$2; shift 2;; --image) IMAGE=$2; shift 2;;
  --key) KEY=$2; shift 2;; --secgroups) SGS=$2; shift 2;; --az) AZ=$2; shift 2;; --rust) RUST=1; shift;; --dry-run) DRY=1; shift;;
  --jupyter) JUPYTER=1; shift;; --python-full) GDAL_IMAGE=ghcr.io/hypertidy/gdal-r-python:latest; shift;; --gdal-image) GDAL_IMAGE=$2; shift 2;;
  *) echo "unknown option $1"; exit 2;; esac; done
[ -n "$KEY" ] || { echo "--key KEYPAIR is required"; exit 2; }
if [ -n "$VOLID$NEWGB" ] && [ -z "$AZ" ]; then echo "--az is required with a volume"; exit 2; fi

if [ -n "$NEWGB" ]; then
  if [ -n "$DRY" ]; then VOLID=DRY-RUN-VOLUME-ID; else
    VOLID=$($O volume create --size "$NEWGB" --availability-zone "$AZ" "$NAME-home" -f value -c id)
    for i in $(seq 40); do [ "$($O volume show "$VOLID" -f value -c status)" = available ] && break; sleep 3; done
  fi
  echo "volume $NAME-home ($NEWGB GB): $VOLID"
fi

UD=$(mktemp "${TMPDIR:-/tmp}/$NAME-userdata.XXXX")
{
  cat <<HEAD
#!/bin/bash
# generated by nectar recipes/launch.sh for $NAME on $(date -u +%FT%TZ)
set -euo pipefail
D=/opt/recipe; mkdir -p \$D; cd \$D
base64 -d <<'B64' | tar xzf -
HEAD
  (cd "$HERE" && tar czf - build.sh layers) | base64 -w 76
  echo B64
  cat <<CONFIG
cat > config <<'CFG'
VOLID='$VOLID' FQDN='$FQDN' EMAIL='$EMAIL' RUST='$RUST' JUPYTER='$JUPYTER' GDAL_IMAGE='$GDAL_IMAGE'
${HOMEDIR:+RECIPE_HOME='$HOMEDIR'}
CFG
CONFIG
  echo "cat > users.tsv <<'USERS'"
  [ -n "$USERS" ] && cat "$USERS"
  echo USERS
  echo 'exec bash build.sh'
} > "$UD"
echo "user-data: $UD ($(wc -c < "$UD") bytes; the limit is 65535 once base64-encoded)"

IFS=, read -ra SG <<< "$SGS"
ARGS=(); for g in "${SG[@]}"; do ARGS+=(--security-group "$g"); done
[ -n "$AZ" ] && ARGS+=(--availability-zone "$AZ")
[ -n "$VOLID" ] && ARGS+=(--block-device "uuid=$VOLID,source_type=volume,destination_type=volume,boot_index=-1,delete_on_termination=false")
CMD=($O server create --image "$IMAGE" --flavor "$FLAVOR" --key-name "$KEY" "${ARGS[@]}" --user-data "$UD" --wait "$NAME" -f value -c addresses)
if [ -n "$DRY" ]; then printf '%q ' "${CMD[@]}"; echo; exit 0; fi
ADDR=$("${CMD[@]}")
IP=$(grep -oE '[0-9]+(\.[0-9]+){3}' <<< "$ADDR" | head -1)
echo "server $NAME: $IP"
echo "follow the build:  ssh ubuntu@$IP tail -f /var/log/recipe-build.log"
echo "then connect:      ssh -L 8787:localhost:8787 ubuntu@$IP   and open http://localhost:8787"
[ -n "$FQDN" ] && echo "add a DNS A record $FQDN -> $IP; the server retries its certificate every 5 min until it resolves"
exit 0
